import { z } from "zod";
import { DIMENSION_KEYS } from "./framework";

export const DIFFICULTIES = ["beginner", "intermediate", "advanced"] as const;
export type Difficulty = (typeof DIFFICULTIES)[number];

export const drillSchema = z.object({
  title: z.string().trim().min(3).max(80),
  summary: z.string().trim().min(10).max(300),
  dimensions: z.array(z.enum(DIMENSION_KEYS)).min(1).max(4),
  difficulty: z.enum(DIFFICULTIES),
  durationMinutes: z.number().int().min(5).max(120),
  players: z.string().trim().min(1).max(40),
  equipment: z.array(z.string().trim().min(1).max(60)).max(8),
  space: z.string().trim().min(1).max(80),
  steps: z.array(z.string().trim().min(3).max(300)).min(1).max(8),
  coachingPoints: z.array(z.string().trim().min(3).max(200)).max(6).default([]),
  progressions: z
    .array(z.object({ level: z.enum(DIFFICULTIES), text: z.string().trim().min(3).max(240) }))
    .max(3)
    .default([]),
  successCriteria: z.string().trim().min(5).max(240),
  safety: z.string().trim().max(240).nullable().default(null),
});
export type DrillContent = z.infer<typeof drillSchema>;
export type Drill = DrillContent & { key: string; source: "starter" | "custom" };

