export const DIFFICULTY_LABEL: Record<Difficulty, string> = { beginner: "Beginner", intermediate: "Intermediate", advanced: "Advanced" };

/** Drills for a dimension, simplest first, so a plan starts where the player can succeed. */
export function drillsFor(dimension: string, library: Drill[], limit = 3): Drill[] {
  const order: Record<Difficulty, number> = { beginner: 0, intermediate: 1, advanced: 2 };
  return library
    .filter((d) => d.dimensions.includes(dimension))
    .sort((a, b) => a.dimensions.indexOf(dimension) - b.dimensions.indexOf(dimension) || order[a.difficulty] - order[b.difficulty])
    .slice(0, limit);
}
